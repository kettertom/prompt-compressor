#!/usr/bin/env node
/**
 * Answer-equivalence check: does the model answer the same way with the
 * compressed prompt as with the original?
 *
 *   cd bench && npm install
 *   ANTHROPIC_API_KEY=... npm run answers                 # default level: low
 *   ANTHROPIC_API_KEY=... LEVEL=very-low MODEL=claude-haiku-4-5 npm run answers
 *
 * For each prompt: sends original and compressed versions with the same
 * probe question (temperature 0), then asks the model to judge whether the
 * two answers are equivalent. Writes answers.json and answers.md.
 * Cost: 3 short calls per prompt (24 total).
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { compress } from '../src/npm-package/index.js';

const here = dirname(fileURLToPath(import.meta.url));
const KEY = process.env.ANTHROPIC_API_KEY;
const MODEL = process.env.MODEL || 'claude-haiku-4-5';
const LEVEL = process.env.LEVEL || 'low';
if (!KEY) {
  console.error('Set ANTHROPIC_API_KEY to run this check.');
  process.exit(1);
}

async function ask(prompt, maxTokens = 600) {
  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'x-api-key': KEY, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: JSON.stringify({ model: MODEL, max_tokens: maxTokens, temperature: 0, messages: [{ role: 'user', content: prompt }] }),
  });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  const data = await res.json();
  return data.content.map((c) => c.text || '').join('').trim();
}

const fill = (text, vars = {}) => Object.entries(vars).reduce((t, [k, v]) => t.split(k).join(v), text);
const facts = JSON.parse(await readFile(join(here, 'facts.json'), 'utf8'));

const results = [];
for (const [file, meta] of Object.entries(facts)) {
  const original = await readFile(join(here, 'prompts', file), 'utf8');
  const compressed = compress(original, LEVEL).output;
  const build = (p) => `${fill(p, meta.vars)}\n\n---\nUser request: ${meta.probe}`;

  const [a, b] = await Promise.all([ask(build(original)), ask(build(compressed))]);
  const verdict = await ask(
    `Two assistants answered the same request. Do the answers agree on every fact, number, decision and instruction that matters? Wording and length differences do not matter.\n\nRequest: ${meta.probe}\n\nAnswer A:\n${a}\n\nAnswer B:\n${b}\n\nReply with exactly "SAME" or "DIFFERENT: <one short reason>".`,
    100,
  );
  const same = verdict.toUpperCase().startsWith('SAME');
  results.push({ file, label: meta.label, same, verdict, answerOriginal: a, answerCompressed: b });
  console.log(`${same ? '✅' : '❌'} ${meta.label}${same ? '' : ' — ' + verdict}`);
}

const ok = results.filter((r) => r.same).length;
const md = `<!-- generated by bench/answers.mjs (${MODEL}, level ${LEVEL}) -->
**Same answer with compressed prompt: ${ok}/${results.length}** (${MODEL}, level \`${LEVEL}\`, temperature 0, judged by the same model)

${results.map((r) => `- ${r.same ? '✅' : '❌'} ${r.label}${r.same ? '' : ` — ${r.verdict}`}`).join('\n')}
`;
await writeFile(join(here, 'answers.md'), md);
await writeFile(join(here, 'answers.json'), JSON.stringify({ model: MODEL, level: LEVEL, results }, null, 2));
console.log(`\n${ok}/${results.length} same. Wrote answers.md and answers.json`);
